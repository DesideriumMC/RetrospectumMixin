package dev.desiderium.retro.mixin.forge;

import java.io.File;
import java.util.Collections;
import com.google.common.eventbus.EventBus;
import cpw.mods.fml.common.DummyModContainer;
import cpw.mods.fml.common.LoadController;
import cpw.mods.fml.common.ModMetadata;

/** Forge-facing metadata; compiled separately to retain Forge's Guava API types. */
public final class RetroMixinModContainer extends DummyModContainer {
    public RetroMixinModContainer() {
        super(metadata());
    }

    private static ModMetadata metadata() {
        ModMetadata metadata = new ModMetadata();
        metadata.modId = "retrospectummixin";
        metadata.name = "Retrospectum Mixin";
        String buildVersion = version();
        int mixinSuffix = buildVersion.indexOf("+mixin.");
        metadata.version = mixinSuffix < 0 ? buildVersion : buildVersion.substring(0, mixinSuffix);
        metadata.description = "Enables Mixin-based mods on Minecraft Forge 1.6.4.";
        if (mixinSuffix >= 0) metadata.description += "\nBundled Mixin " + buildVersion.substring(mixinSuffix + 7) + ".";
        metadata.authorList = Collections.singletonList("DesideriumMC");
        metadata.url = "https://github.com/DesideriumMC/RetrospectumMixin";
        metadata.credits = "SpongePowered Mixin and contributors.";
        metadata.autogenerated = false;
        return metadata;
    }

    private static File source() {
        try {
            java.net.URL location = RetroMixinModContainer.class.getProtectionDomain().getCodeSource().getLocation();
            if ("jar".equals(location.getProtocol())) {
                location = ((java.net.JarURLConnection) location.openConnection()).getJarFileURL();
            }
            return new File(location.toURI());
        } catch (Exception e) {
            throw new IllegalStateException("Cannot locate the Retrospectum Mixin archive", e);
        }
    }

    private static String version() {
        File source = source();
        if (!source.isFile()) return "development";
        try {
            java.util.jar.JarFile jar = new java.util.jar.JarFile(source);
            try {
                String version = jar.getManifest().getMainAttributes().getValue("Implementation-Version");
                return version == null ? "development" : version;
            } finally { jar.close(); }
        } catch (java.io.IOException e) {
            throw new IllegalStateException("Cannot read the Retrospectum Mixin version", e);
        }
    }

    @Override public File getSource() { return source(); }

    @Override public boolean registerBus(EventBus bus, LoadController controller) {
        bus.register(this);
        return true;
    }
}
