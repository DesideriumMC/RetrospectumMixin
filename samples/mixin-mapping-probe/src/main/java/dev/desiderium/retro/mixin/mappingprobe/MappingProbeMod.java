package dev.desiderium.retro.mixin.mappingprobe;

import cpw.mods.fml.common.Mod;
import cpw.mods.fml.common.event.FMLInitializationEvent;
import dev.desiderium.retro.mixin.mappingprobe.mixin.StackAccess;
import net.minecraft.item.Item;
import net.minecraft.item.ItemFood;
import net.minecraft.item.ItemStack;

@Mod(modid = "retromixinp2", name = "RetroMixin P2 Mapping Probe", version = "0.1.0-p2")
public final class MappingProbeMod {
    public static boolean injected, redirected, overwritten, inherited;

    @Mod.EventHandler
    public void init(FMLInitializationEvent event) {
        cpw.mods.fml.common.ModContainer bootstrap = cpw.mods.fml.common.Loader.instance()
            .getIndexedModList().get("retrospectummixin");
        check(bootstrap != null, "Bootstrap listed exactly once");
        int count = 0;
        for (cpw.mods.fml.common.ModContainer mod : cpw.mods.fml.common.Loader.instance().getModList()) {
            if ("retrospectummixin".equals(mod.getModId())) count++;
        }
        check(count == 1 && "Retrospectum Mixin".equals(bootstrap.getName()), "Bootstrap metadata");
        check(cpw.mods.fml.common.Loader.instance().getActiveModList().contains(bootstrap), "Bootstrap active");
        check(!bootstrap.getVersion().contains("+mixin.") && bootstrap.getMetadata().description.contains("Mixin 0.8.7")
            && !bootstrap.getMetadata().autogenerated,
            "Bootstrap version and description");
        ItemStack stack = new ItemStack(Item.appleRed);
        StackAccess access = (StackAccess) (Object) stack;
        check(access.retromixin$getItemId() == Item.appleRed.itemID, "Accessor");
        check(access.retromixin$invokeGetItem() == Item.appleRed, "Invoker descriptor");
        check(stack.getMaxStackSize() == 64 && injected && redirected, "Inject Redirect Shadow");
        check(stack.isStackable() && overwritten, "Overwrite extra mapping");
        check(((ItemFood) Item.appleRed).getHealAmount() > 0 && inherited, "Inherited member");
        System.out.println("[RETROMIXIN-P2] ALL MEMBER CHECKS PASSED");
    }

    public static void check(boolean result, String name) {
        if (!result) throw new IllegalStateException("[RETROMIXIN-P2] FAILED " + name);
        System.out.println("[RETROMIXIN-P2] PASS " + name);
    }
}
